//! Per-analysis sessions and confined source lookup for the OpenHeart server.
//!
//! Each analysis writes into its own directory under `<workspace>/sessions`, and the web
//! studio reaches it through a session cookie, so one client's results are never served
//! to another and the shipped `web/diagrams` samples are never overwritten. Source
//! lookups (`/api/source`) resolve only against the files an analysis (or a configured
//! sample root) actually indexed, re-verifying containment at read time.

#![forbid(unsafe_code)]

use std::collections::{BTreeMap, HashMap, VecDeque};
use std::fs;
use std::io;
use std::path::{Path, PathBuf};
use std::sync::{Arc, Mutex, MutexGuard};
use std::time::SystemTime;

use crate::adapters::runner::{canonicalize_clean, SourceInventory};
use crate::core::logger::{log_info, log_warn};

/// Prefix of session identifiers and session directory names.
pub(crate) const SESSION_PREFIX: &str = "sess_";

/// Whether `id` has the shape of a session identifier generated by this server.
pub(crate) fn is_session_id(id: &str) -> bool {
    id.strip_prefix(SESSION_PREFIX).is_some_and(|rest| {
        !rest.is_empty() && rest.len() <= 64 && rest.bytes().all(|byte| byte.is_ascii_hexdigit())
    })
}

/// Result of resolving a client-supplied source path.
#[derive(Debug)]
pub(crate) enum SourceLookup {
    /// The file and its root-relative path.
    Found { relative: String, content: String },
    /// No indexed file matches.
    NotFound,
    /// Several indexed files match a bare name; their relative paths.
    Ambiguous(Vec<String>),
    /// The request is not a relative path inside the root.
    Invalid(&'static str),
    /// The file matched but can no longer be read safely.
    Unreadable,
}

/// The source files one analysis may serve, keyed by root-relative path.
#[derive(Debug)]
pub(crate) struct SourceIndex {
    root: PathBuf,
    files: BTreeMap<String, PathBuf>,
    by_name: HashMap<String, Vec<String>>,
    by_stem: HashMap<String, Vec<String>>,
    max_file_bytes: u64,
}

impl SourceIndex {
    /// Indexes the files of `inventory`.
    pub fn from_inventory(inventory: &SourceInventory) -> Self {
        let mut index = Self {
            root: inventory.root.clone(),
            files: BTreeMap::new(),
            by_name: HashMap::new(),
            by_stem: HashMap::new(),
            max_file_bytes: inventory.options.limits.max_file_bytes,
        };
        for file in &inventory.files {
            let name = file
                .relative
                .rsplit('/')
                .next()
                .unwrap_or(&file.relative)
                .to_string();
            let stem = name
                .rsplit_once('.')
                .map(|(stem, _)| stem.to_string())
                .unwrap_or_else(|| name.clone());
            index
                .by_name
                .entry(name)
                .or_default()
                .push(file.relative.clone());
            index
                .by_stem
                .entry(stem)
                .or_default()
                .push(file.relative.clone());
            index.files.insert(file.relative.clone(), file.path.clone());
        }
        index
    }

    /// Number of indexed files.
    pub fn len(&self) -> usize {
        self.files.len()
    }

    /// Resolves `requested` (root-relative path, path suffix, file name, or class name).
    pub fn lookup(&self, requested: &str) -> SourceLookup {
        let normalized = match normalize_request(requested) {
            Ok(normalized) => normalized,
            Err(reason) => return SourceLookup::Invalid(reason),
        };
        if let Some(path) = self.files.get(&normalized) {
            return self.read(&normalized, path);
        }

        let suffix = format!("/{}", normalized);
        let mut candidates: Vec<&String> = self
            .files
            .keys()
            .filter(|relative| relative.ends_with(&suffix))
            .collect();
        if candidates.is_empty() && !normalized.contains('/') {
            let matches = self
                .by_name
                .get(&normalized)
                .or_else(|| self.by_stem.get(&normalized));
            if let Some(list) = matches {
                candidates = list.iter().collect();
            }
        }
        match candidates.as_slice() {
            [] => SourceLookup::NotFound,
            [only] => match self.files.get(*only) {
                Some(path) => self.read(only, path),
                None => SourceLookup::NotFound,
            },
            many => {
                let relatives = many.iter().map(|relative| relative.to_string()).collect();
                SourceLookup::Ambiguous(relatives)
            }
        }
    }

    fn read(&self, relative: &str, path: &Path) -> SourceLookup {
        // Re-resolve at read time: the tree may have changed since it was indexed.
        let canonical = match canonicalize_clean(path) {
            Ok(canonical) if canonical.starts_with(&self.root) => canonical,
            _ => return SourceLookup::Unreadable,
        };
        match fs::metadata(&canonical) {
            Ok(meta) if meta.is_file() && meta.len() <= self.max_file_bytes => {}
            _ => return SourceLookup::Unreadable,
        }
        match fs::read(&canonical) {
            Ok(bytes) => SourceLookup::Found {
                relative: relative.to_string(),
                content: String::from_utf8_lossy(&bytes).into_owned(),
            },
            Err(_) => SourceLookup::Unreadable,
        }
    }
}

/// Normalizes a requested path to `a/b/C.java` form, rejecting absolute paths, drive or
/// UNC prefixes, `..` segments and control characters.
fn normalize_request(requested: &str) -> Result<String, &'static str> {
    let unified = requested.trim().replace('\\', "/");
    if unified.is_empty() {
        return Err("the requested path is empty");
    }
    if unified.chars().any(char::is_control) {
        return Err("the requested path contains control characters");
    }
    if unified.starts_with('/') {
        return Err("absolute paths are not accepted; send a path relative to the source root");
    }
    let bytes = unified.as_bytes();
    if bytes.len() >= 2 && bytes[1] == b':' {
        return Err("drive-qualified paths are not accepted");
    }
    let mut segments = Vec::new();
    for segment in unified.split('/') {
        match segment {
            "" | "." => continue,
            ".." => return Err("'..' segments are not accepted"),
            other => segments.push(other),
        }
    }
    if segments.is_empty() {
        return Err("the requested path is empty");
    }
    Ok(segments.join("/"))
}

/// One completed analysis.
#[derive(Debug)]
pub(crate) struct AnalysisSession {
    /// Session identifier (also the directory name).
    pub id: String,
    /// Directory holding artifacts, `diagrams/` and `run.json`.
    pub dir: PathBuf,
    /// Files the session may serve through `/api/source`.
    pub sources: SourceIndex,
    /// Client-facing summary returned by `/api/sessions/<id>`.
    pub summary: serde_json::Value,
    /// Completion time.
    pub created: SystemTime,
}

/// Bounded, most-recent-first store of analysis sessions.
pub(crate) struct SessionStore {
    root: PathBuf,
    max_sessions: usize,
    entries: Mutex<VecDeque<Arc<AnalysisSession>>>,
}

impl SessionStore {
    /// Opens the store at `root`, removing session directories left by earlier processes
    /// (their in-memory index is gone, so nothing can reference them).
    pub fn open(root: PathBuf, max_sessions: usize) -> io::Result<Self> {
        fs::create_dir_all(&root)?;
        for entry in fs::read_dir(&root)? {
            let entry = entry?;
            let name = entry.file_name().to_string_lossy().into_owned();
            if is_session_id(&name) && entry.file_type()?.is_dir() {
                if let Err(err) = fs::remove_dir_all(entry.path()) {
                    log_warn(&format!(
                        "Could not remove stale session '{}': {}",
                        name, err
                    ));
                }
            }
        }
        Ok(Self {
            root,
            max_sessions: max_sessions.max(1),
            entries: Mutex::new(VecDeque::new()),
        })
    }

    fn entries(&self) -> MutexGuard<'_, VecDeque<Arc<AnalysisSession>>> {
        self.entries
            .lock()
            .unwrap_or_else(|poisoned| poisoned.into_inner())
    }

    /// Creates the directory for session `id`; fails if it already exists.
    pub fn allocate(&self, id: &str) -> io::Result<PathBuf> {
        let dir = self.root.join(id);
        fs::create_dir(&dir)?;
        Ok(dir)
    }

    /// Registers a completed session, evicting (and deleting) the oldest beyond capacity.
    pub fn insert(&self, session: AnalysisSession) -> Arc<AnalysisSession> {
        let session = Arc::new(session);
        let evicted: Vec<Arc<AnalysisSession>> = {
            let mut entries = self.entries();
            entries.push_back(Arc::clone(&session));
            let excess = entries.len().saturating_sub(self.max_sessions);
            entries.drain(..excess).collect()
        };
        for old in evicted {
            log_info(&format!("Evicting analysis session {}", old.id));
            Self::remove_dir(&old.dir);
        }
        session
    }

    /// Looks up a session by id.
    pub fn get(&self, id: &str) -> Option<Arc<AnalysisSession>> {
        if !is_session_id(id) {
            return None;
        }
        self.entries()
            .iter()
            .find(|session| session.id == id)
            .cloned()
    }

    /// Deletes the directory of a session that will never be registered.
    pub fn discard(&self, dir: &Path) {
        Self::remove_dir(dir);
    }

    fn remove_dir(dir: &Path) {
        if let Err(err) = fs::remove_dir_all(dir) {
            if err.kind() != io::ErrorKind::NotFound {
                log_warn(&format!(
                    "Could not remove session directory '{}': {}",
                    dir.display(),
                    err
                ));
            }
        }
    }
}
